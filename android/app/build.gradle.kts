import java.util.Properties

plugins {
    id("com.android.application")
    id("org.jetbrains.kotlin.android")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

// Signing: android/key.properties (git-ignored, local builds) wins; CI exports the SIGNING_* env vars instead.
val keyProperties = Properties()
val keyPropertiesFile = rootProject.file("key.properties")
if (keyPropertiesFile.exists()) {
    keyPropertiesFile.reader(Charsets.UTF_8).use { keyProperties.load(it) }
}

fun signingSecret(property: String, envVar: String): String? =
    keyProperties.getProperty(property) ?: System.getenv(envVar)

android {
    // The Kotlin package and manifest namespace keep the upstream name; only applicationId is ours.
    namespace = "me.efesser.flauncher"
    compileSdk = flutter.compileSdkVersion
    ndkVersion = flutter.ndkVersion

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    defaultConfig {
        applicationId = "dev.neugebauer.tvlauncher"
        minSdk = flutter.minSdkVersion
        targetSdk = flutter.targetSdkVersion
        versionCode = flutter.versionCode
        versionName = flutter.versionName
    }

    signingConfigs {
        create("release") {
            storeFile = file("upload-keystore.jks")
            storePassword = signingSecret("storePassword", "SIGNING_KEYSTORE_PASSWORD")
            keyAlias = signingSecret("keyAlias", "SIGNING_KEY_ALIAS")
            keyPassword = signingSecret("keyPassword", "SIGNING_KEY_PASSWORD")
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.getByName("release")
        }
    }
}

kotlin {
    compilerOptions {
        jvmTarget = org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17
    }
}

